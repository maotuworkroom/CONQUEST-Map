function prefInfo(data){
  const info={};
  for(const id in data.prefs){
    const p=data.prefs[id];
    let best=0;
    for(const rec of p.records){ if(rec.type>best) best=rec.type; }
    info[id]={best,count:p.records.length,records:p.records};
  }
  return info;
}
function achGot(ach,info,manual){
  if(ach.kind==='group'){
    return ach.groups.some(g=>g.every(id=>info[id] && info[id].best>=ach.level));
  }
  if(ach.kind==='count'){
    const n=ach.prefs.filter(id=>info[id] && info[id].best>=ach.level).length;
    return n>=ach.n;
  }
  if(ach.kind==='manual'){
    return manual.includes(ach.id);
  }
  return false;
}
function computeScore(data){
  const info=prefInfo(data);
  const manual=data.ach?data.ach.manual||[]:[];
  let base=0, repeat=0;
  for(const id in info){
    if(info[id].best>0) base += TYPE_PTS[info[id].best];
    if(info[id].count>1) repeat += 2*(info[id].count-1);
  }
  let region=0;
  for(const rk in REGIONS){
    const ids=REGIONS[rk].ids;
    if(ids.every(id=>info[id] && info[id].best>=1)) region+=10;
    if(ids.every(id=>info[id] && info[id].best>=3)) region+=15;
  }
  const achList=ACH.map(a=>({a,got:achGot(a,info,manual)}));
  const achPts=achList.reduce((s,x)=>s+(x.got?x.a.pts:0),0);
  const total=base+repeat+region+achPts;
  return {total,base,repeat,region,achPts,info,achList};
}
function levelOf(pts){
  let lv=LEVELS[0], idx=0;
  for(let i=0;i<LEVELS.length;i++){ if(pts>=LEVELS[i].pts){ lv=LEVELS[i]; idx=i; } }
  return {lv,idx,next:LEVELS[idx+1]||null,prev:LEVELS[Math.max(0,idx-1)]};
}
